<?php
header('Content-Type: application/json');
error_reporting(0);

// Prevent altering settings from outside the local network
$w34_local_only_message = json_encode(['error' => 'Saving overrides is only allowed from the local network.']);
include_once __DIR__ . '/local_only.php';

$raw = file_get_contents('php://input');
$data = json_decode($raw, true);

if (!is_array($data)) {
    $raw_post = $_POST['overrides'] ?? '';
    if ($raw_post) {
        $data = json_decode($raw_post, true);
    }
}

if (!is_array($data)) {
    http_response_code(400);
    echo json_encode(['error' => 'Invalid JSON received']);
    exit;
}

$json_str = json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);
$js_content = "/* Auto-generated by sandbox.php — Highcharts visual overrides */\nwindow.w34HighchartsOverrides = " . $json_str . ";\n";

$target_file = __DIR__ . '/w34highcharts/scripts/sandbox-overrides.js';
if (file_put_contents($target_file, $js_content) === false) {
    http_response_code(500);
    echo json_encode(['error' => 'Failed to write overrides file']);
    exit;
}

echo json_encode(['success' => true, 'overrides' => $data]);
